int main(void)
{

  /* USER CODE BEGIN 1 */
  /* USER CODE END 1 */

  /* MCU Configuration--------------------------------------------------------*/

  /* Reset of all peripherals, Initializes the Flash interface and the Systick. */
  HAL_Init();

  /* USER CODE BEGIN Init */
  /* USER CODE END Init */

  /* Configure the system clock */
  SystemClock_Config();

  /* USER CODE BEGIN SysInit */
  /* USER CODE END SysInit */

  /* Initialize all configured peripherals */
  MX_GPIO_Init();
  MX_USART2_UART_Init();
  MX_TIM1_Init();
  MX_TIM2_Init();
  MX_I2C1_Init();\
  MX_USART1_UART_Init();
  /* USER CODE BEGIN 2 */

 Button_Init();
  Conveyor_Init();
  Sorter_Init();

  lcd_ok = LCD_Init();

#if CONVEYOR_TEST_MODE
  Conveyor_Run(40);
#else
  Communication_Init();
#endif

  /* USER CODE END 2 */

  /* Infinite loop */
  /* USER CODE BEGIN WHILE */

while (1)
{
    /* USER CODE END WHILE */

    /* USER CODE BEGIN 3 */
#if CONVEYOR_TEST_MODE
    // Sensor and communication control are temporarily excluded.
    button_raw = Button_ReadRaw();
    if (Button_WasPressed())
    {
        test_running ^= 1U;
        if (test_running) Conveyor_Run(40);
        else Conveyor_Stop();
    }
#else
    Communication_Update();

    if (startup_run_pending &&
        Wifi_IsReady() &&
        !Sorter_IsStopped())
    {
        startup_run_pending = 0U;
        Conveyor_Run(40);
        Communication_ReportState("RUN");
    }

    sensor1_raw = Tracking_Read1();
    sensor2_raw = Tracking_Read2();
    sensor3_raw = Tracking_Read3();

    sensor1_detected = Tracking_IsDetected1();
    sensor2_detected = Tracking_IsDetected2();
    sensor3_detected = Tracking_IsDetected3();

    if (sensor1_previous == 0U &&
        sensor1_detected == 1U)
    {
        sensor1_count++;
    }

    sensor1_previous = sensor1_detected;

    button_raw = Button_ReadRaw();

    if (Button_WasPressed())
    {
        startup_run_pending = 0U;

        if (!Sorter_IsStopped())
        {
            Sorter_Stop();
        }
        else if (!Wifi_IsReady())
        {
            LCD_ShowResetBlocked();
        }
        else if (Sorter_TryReset())
        {
            LCD_ClearResetBlocked();
            Conveyor_Run(40);

            Communication_ReportState("RESTART");
            Communication_ReportState("RUN");
        }
        else
        {
            LCD_ShowResetBlocked();
        }
    }

    Sorter_Update();

    sorter_error = Sorter_GetError();
    normal_completed = Sorter_GetNormalCount();
    defect_completed = Sorter_GetDefectCount();
    pending_products = Sorter_GetPendingCount();

    LCD_Update();
#endif
    HAL_Delay(10);
}

  /* USER CODE END 3 */
}

